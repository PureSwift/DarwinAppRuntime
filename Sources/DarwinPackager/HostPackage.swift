import Foundation

/// The SwiftPM package that builds the app's executable (step 5): an
/// executable target over `DarwinHostApp`, linked with the app's
/// `libapp.a`.
///
/// Until releases ship a prebuilt `DarwinHost.a` (§5), the packager builds
/// the host from source this way, in its work directory.
///
/// The build uses `swift build` with the Swift Build engine, cross-compiling
/// for iOS with `--triple` and `--sdk`. Neither `swift build` nor
/// `xcodebuild` on a package records the SDK's version in the executable's
/// `LC_BUILD_VERSION` (it writes the deployment target), so the package
/// passes the linker `-platform_version` with the SDK's real version; the
/// last one wins.
public struct HostPackage: Equatable, Sendable {

    /// The executable target's name. It's fixed, not the app's executable
    /// name, which could collide with a target of AppRuntime's (such as
    /// `ExampleApp`); the packager renames the binary.
    public static let targetName = "AppExecutable"

    /// `main.swift`.
    public static let mainSwift = """
        import DarwinHostApp

        HostApp.run(AppEntryPoints(main: rt_main, dispatch: rt_dispatch, finalize: rt_finalize))

        """

    /// DarwinAppRuntime's checkout, the one this packager is built from.
    public static var defaultHostPackage: URL {
        // Sources/DarwinPackager/HostPackage.swift
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
    }

    /// DarwinAppRuntime's checkout.
    public var hostPackage: URL

    /// The app's library: a native slice or wasm2c output.
    public var library: URL

    public var platform: ApplePlatform

    /// The minimum OS of the built platform.
    public var deploymentTarget: String

    /// The SDK version written into the executable.
    public var sdkVersion: String

    public init(hostPackage: URL, library: URL, platform: ApplePlatform, deploymentTarget: String, sdkVersion: String) {
        self.hostPackage = hostPackage
        self.library = library
        self.platform = platform
        self.deploymentTarget = deploymentTarget
        self.sdkVersion = sdkVersion
    }

    /// The name SwiftPM knows the host package by: its directory's.
    public var hostPackageIdentity: String {
        hostPackage.lastPathComponent
    }

    /// `Package.swift`.
    public var manifest: String {
        let iOS = platform.isMac ? ApplePlatform.ios.hostMinimum : deploymentTarget
        let macOS = platform.isMac ? deploymentTarget : ApplePlatform.macos.hostMinimum
        let flags = [
            library.path,
            "-Xlinker", "-platform_version",
            "-Xlinker", platform.linkerName,
            "-Xlinker", deploymentTarget,
            "-Xlinker", sdkVersion,
        ]
        return """
            // swift-tools-version:6.0
            // Generated by darwin-app for \(platform.rawValue); `darwin-app package` rewrites it.
            import PackageDescription

            let package = Package(
                name: "AppHost",
                platforms: [
                    .iOS(\(literal(iOS))),
                    .macOS(\(literal(macOS))),
                ],
                dependencies: [
                    .package(path: \(literal(hostPackage.path))),
                ],
                targets: [
                    .executableTarget(
                        name: \(literal(Self.targetName)),
                        dependencies: [
                            .product(name: "DarwinHostApp", package: \(literal(hostPackageIdentity))),
                        ],
                        linkerSettings: [
                            .unsafeFlags([
            \(flags.map { "                    \(literal($0))," }.joined(separator: "\n"))
                            ]),
                        ]
                    ),
                ]
            )

            """
    }

    /// Writes the package into `directory`, leaving files that are already
    /// up to date untouched, so SwiftPM doesn't reload the manifest.
    ///
    /// The host package's `.swift-version` (for swiftly) and
    /// `Package.resolved` come along, so the build uses the same toolchain
    /// and dependency versions as the host's own.
    public func write(to directory: URL) throws {
        let fileManager = FileManager.default
        let sources = directory.appendingPathComponent("Sources/\(Self.targetName)")
        try fileManager.createDirectory(at: sources, withIntermediateDirectories: true)
        try Self.update(directory.appendingPathComponent("Package.swift"), manifest)
        try Self.update(sources.appendingPathComponent("main.swift"), Self.mainSwift)
        for name in [".swift-version", "Package.resolved"] {
            let source = hostPackage.appendingPathComponent(name)
            let destination = directory.appendingPathComponent(name)
            if fileManager.fileExists(atPath: source.path), !fileManager.fileExists(atPath: destination.path) {
                try fileManager.copyItem(at: source, to: destination)
            }
        }
    }

    static func update(_ url: URL, _ text: String) throws {
        if let existing = try? String(contentsOf: url, encoding: .utf8), existing == text {
            return
        }
        try text.write(to: url, atomically: true, encoding: .utf8)
    }

    /// `swift build`'s arguments after `build`, without `--show-bin-path`.
    public func buildArguments(directory: URL, configuration: BuildConfiguration, architectures: [String], sdkPath: String) -> [String] {
        var arguments = ["build", "-c", configuration.rawValue, "--package-path", directory.path, "--product", Self.targetName]
        switch platform {
        case .ios, .iosSimulator:
            // One architecture: --triple doesn't combine with --arch.
            let architecture = architectures.first ?? "arm64"
            arguments += ["--triple", platform.triple(architecture: architecture, minimum: deploymentTarget), "--sdk", sdkPath]
        case .macos:
            for architecture in architectures {
                arguments += ["--arch", architecture]
            }
        }
        return arguments
    }

    /// The build, streaming its output.
    ///
    /// - Parameters:
    ///   - swift: the `swift` command, by default Xcode's through `xcrun`.
    ///   - environment: added to the build's, such as `APPRUNTIME_PATH`.
    public func buildCommand(
        directory: URL,
        configuration: BuildConfiguration,
        architectures: [String],
        sdkPath: String,
        swift: [String],
        environment: [String: String]
    ) -> Command {
        Command(
            swift[0],
            Array(swift.dropFirst()) + buildArguments(directory: directory, configuration: configuration, architectures: architectures, sdkPath: sdkPath),
            environment: environment,
            directory: directory.path,
            streamsOutput: true
        )
    }

    /// The same build's `--show-bin-path`, where the executable lands.
    public func binPathCommand(
        directory: URL,
        configuration: BuildConfiguration,
        architectures: [String],
        sdkPath: String,
        swift: [String],
        environment: [String: String]
    ) -> Command {
        Command(
            swift[0],
            Array(swift.dropFirst()) + buildArguments(directory: directory, configuration: configuration, architectures: architectures, sdkPath: sdkPath) + ["--show-bin-path"],
            environment: environment,
            directory: directory.path
        )
    }
}

/// A Swift string literal.
func literal(_ text: String) -> String {
    var result = "\""
    for scalar in text.unicodeScalars {
        switch scalar {
        case "\"": result += "\\\""
        case "\\": result += "\\\\"
        case "\n": result += "\\n"
        default: result.unicodeScalars.append(scalar)
        }
    }
    return result + "\""
}
