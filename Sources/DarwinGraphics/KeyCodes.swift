import DynamicGraphics

/// Keys as `SurfaceDelegate.key` reports them: USB HID usage IDs
/// (`DynamicRuntime.md` §8.6). `UIKey.keyCode` already is one; macOS's
/// virtual key codes (`kVK_…`, `NSEvent.keyCode`) are mapped here.
enum KeyCodes {

    /// The HID usage of a macOS virtual key code, or `nil` for keys without
    /// one, such as Fn.
    static func hidUsage(macKeyCode code: UInt16) -> Int32? {
        macKeys[code]
    }

    /// `kVK_…` → HID usage, Keyboard/Keypad page.
    static let macKeys: [UInt16: Int32] = [
        // Letters.
        0x00: 0x04, 0x0B: 0x05, 0x08: 0x06, 0x02: 0x07, 0x0E: 0x08, 0x03: 0x09,
        0x05: 0x0A, 0x04: 0x0B, 0x22: 0x0C, 0x26: 0x0D, 0x28: 0x0E, 0x25: 0x0F,
        0x2E: 0x10, 0x2D: 0x11, 0x1F: 0x12, 0x23: 0x13, 0x0C: 0x14, 0x0F: 0x15,
        0x01: 0x16, 0x11: 0x17, 0x20: 0x18, 0x09: 0x19, 0x0D: 0x1A, 0x07: 0x1B,
        0x10: 0x1C, 0x06: 0x1D,
        // The top row's digits.
        0x12: 0x1E, 0x13: 0x1F, 0x14: 0x20, 0x15: 0x21, 0x17: 0x22, 0x16: 0x23,
        0x1A: 0x24, 0x1C: 0x25, 0x19: 0x26, 0x1D: 0x27,
        // Return, Escape, Delete (backspace), Tab, Space and punctuation.
        0x24: 0x28, 0x35: 0x29, 0x33: 0x2A, 0x30: 0x2B, 0x31: 0x2C,
        0x1B: 0x2D, 0x18: 0x2E, 0x21: 0x2F, 0x1E: 0x30, 0x2A: 0x31,
        0x29: 0x33, 0x27: 0x34, 0x32: 0x35, 0x2B: 0x36, 0x2F: 0x37, 0x2C: 0x38,
        0x39: 0x39, // Caps Lock
        0x0A: 0x64, // ISO §, the key left of 1 on ISO keyboards
        // F1…F20.
        0x7A: 0x3A, 0x78: 0x3B, 0x63: 0x3C, 0x76: 0x3D, 0x60: 0x3E, 0x61: 0x3F,
        0x62: 0x40, 0x64: 0x41, 0x65: 0x42, 0x6D: 0x43, 0x67: 0x44, 0x6F: 0x45,
        0x69: 0x68, 0x6B: 0x69, 0x71: 0x6A, 0x6A: 0x6B, 0x40: 0x6C, 0x4F: 0x6D,
        0x50: 0x6E, 0x5A: 0x6F,
        // Navigation: Help is where Insert is.
        0x72: 0x49, 0x73: 0x4A, 0x74: 0x4B, 0x75: 0x4C, 0x77: 0x4D, 0x79: 0x4E,
        0x7C: 0x4F, 0x7B: 0x50, 0x7D: 0x51, 0x7E: 0x52,
        // Keypad: Clear is Num Lock's place.
        0x47: 0x53, 0x4B: 0x54, 0x43: 0x55, 0x4E: 0x56, 0x45: 0x57, 0x4C: 0x58,
        0x53: 0x59, 0x54: 0x5A, 0x55: 0x5B, 0x56: 0x5C, 0x57: 0x5D, 0x58: 0x5E,
        0x59: 0x5F, 0x5B: 0x60, 0x5C: 0x61, 0x52: 0x62, 0x41: 0x63, 0x51: 0x67,
        // Media and the menu key.
        0x6E: 0x65, 0x4A: 0x7F, 0x48: 0x80, 0x49: 0x81,
        // JIS.
        0x5F: 0x85, 0x5E: 0x87, 0x68: 0x90, 0x66: 0x91, 0x5D: 0x89,
        // Modifiers.
        0x3B: 0xE0, 0x38: 0xE1, 0x3A: 0xE2, 0x37: 0xE3,
        0x3E: 0xE4, 0x3C: 0xE5, 0x3D: 0xE6, 0x36: 0xE7,
    ]

    /// A modifier key's bit in `NSEvent.modifierFlags`' device-dependent
    /// part (`NX_DEVICE…KEYMASK`), which tells left from right: whether it
    /// is down after a `flagsChanged`.
    static let macModifierMasks: [UInt16: UInt] = [
        0x3B: 0x0000_0001, // left control
        0x38: 0x0000_0002, // left shift
        0x3C: 0x0000_0004, // right shift
        0x37: 0x0000_0008, // left command
        0x36: 0x0000_0010, // right command
        0x3A: 0x0000_0020, // left option
        0x3D: 0x0000_0040, // right option
        0x3E: 0x0000_2000, // right control
    ]

    /// `KeyModifiers` from the device-independent modifier flags: shift
    /// `1 << 17`, control `1 << 18`, option `1 << 19`, command `1 << 20`,
    /// which `NSEvent.ModifierFlags` and `UIKeyModifierFlags` share.
    static func modifiers(flags: UInt) -> KeyModifiers {
        var modifiers: KeyModifiers = []
        if flags & (1 << 17) != 0 { modifiers.insert(.shift) }
        if flags & (1 << 18) != 0 { modifiers.insert(.control) }
        if flags & (1 << 19) != 0 { modifiers.insert(.alt) }
        if flags & (1 << 20) != 0 { modifiers.insert(.meta) }
        return modifiers
    }
}
